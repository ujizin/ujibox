#!/usr/bin/env python3
"""Draws the ujibox mascot, a toolbox with a face, and writes every icon file.

The shapes are in a 100 x 100 design space. The script writes:
  art/logo.svg                     the repository logo (rounded tile)
  docs/assets/logo.svg             the same logo, for the docs site
  art/icon.svg                     the full-bleed tile (iOS masks the corners)
  app/androidApp/.../drawable/     the adaptive icon layers, as vector drawables
  app/iosApp/.../AppIcon.png       the 1024 px iOS icon (needs rsvg-convert)

Run it from any directory: python3 art/generate_icons.py
"""
import os
import shutil
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The colors of the app theme (seed #D92F2F).
RED_TOP, RED_BOTTOM = "#E03A3A", "#C42626"
LID_TOP, LID_BOTTOM = "#C41C22", "#A00D16"
METAL = "#F3D9D6"
EYE = "#FFF8F7"
PUPIL = "#1E0F0E"
MOUTH = "#3A0A0C"
TONGUE = "#FC8278"
TONGUE_LINE = "#E0645B"
CHEEK = "#FF8A80"
BG_TOP, BG_BOTTOM = "#2E2B2B", "#0D0B0B"


def rrect(x0, y0, x1, y1, r):
    return (f"M{x0 + r},{y0} H{x1 - r} A{r},{r} 0 0 1 {x1},{y0 + r} V{y1 - r} "
            f"A{r},{r} 0 0 1 {x1 - r},{y1} H{x0 + r} A{r},{r} 0 0 1 {x0},{y1 - r} "
            f"V{y0 + r} A{r},{r} 0 0 1 {x0 + r},{y0} Z")


def circle(cx, cy, r):
    return f"M{cx - r},{cy} A{r},{r} 0 1 0 {cx + r},{cy} A{r},{r} 0 1 0 {cx - r},{cy} Z"


def ellipse(cx, cy, rx, ry):
    return f"M{cx - rx},{cy} A{rx},{ry} 0 1 0 {cx + rx},{cy} A{rx},{ry} 0 1 0 {cx - rx},{cy} Z"


HANDLE = rrect(35, 17, 65, 33, 7) + " " + rrect(40.5, 22.5, 59.5, 33, 2.5)
BODY = rrect(18, 38, 82, 82, 9)
LID = rrect(15, 29, 85, 45, 6)
LID_SHINE = rrect(20, 31.5, 80, 33.8, 1.15)
LATCHES = [rrect(26, 42, 33, 50, 1.6), rrect(67, 42, 74, 50, 1.6)]
EYES = [circle(38.5, 58, 6.6), circle(61.5, 58, 6.6)]
PUPILS = [circle(40, 59, 3.5), circle(63, 59, 3.5)]
GLINTS = [circle(41.3, 57.4, 1.25), circle(64.3, 57.4, 1.25)]
CHEEKS = [ellipse(29, 67, 3.6, 2.4), ellipse(71, 67, 3.6, 2.4)]
MOUTH_PATH = "M41,66 Q50,67.5 59,66 Q58.2,74.5 50,74.5 Q41.8,74.5 41,66 Z"
TONGUE_PATH = "M45,70.5 Q50,67.8 55,70.5 L55,77 Q55,81.5 50,81.5 Q45,81.5 45,77 Z"
TONGUE_SPLIT = "M49.4,71.5 H50.6 V77.5 Q50,78.5 49.4,77.5 Z"
SHADOW = ellipse(50, 86, 31, 3.6)

# (path, fill, alpha, gradient) in drawing order. A gradient is (top, bottom, y0, y1).
SHAPES = (
    [(SHADOW, "#000000", 0.45, None),
     (HANDLE, METAL, 1, None),
     (BODY, None, 1, (RED_TOP, RED_BOTTOM, 38, 82)),
     (LID, None, 1, (LID_TOP, LID_BOTTOM, 29, 45)),
     (LID_SHINE, "#FFFFFF", 0.18, None)]
    + [(p, METAL, 1, None) for p in LATCHES]
    + [(p, CHEEK, 0.45, None) for p in CHEEKS]
    + [(p, EYE, 1, None) for p in EYES]
    + [(p, PUPIL, 1, None) for p in PUPILS]
    + [(p, EYE, 1, None) for p in GLINTS]
    + [(MOUTH_PATH, MOUTH, 1, None), (TONGUE_PATH, TONGUE, 1, None), (TONGUE_SPLIT, TONGUE_LINE, 1, None)]
)

# The handle has a hole; every other shape is plain.
EVEN_ODD = {HANDLE}


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    return path


def svg(rounded):
    defs = [f'<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">'
            f'<stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient>',
            '<radialGradient id="glow" cx="0.5" cy="0.42" r="0.55">'
            '<stop offset="0" stop-color="#FFFFFF" stop-opacity="0.07"/>'
            '<stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient>']
    body = []
    for i, (d, fill, alpha, grad) in enumerate(SHAPES):
        if grad:
            gid = f"g{i}"
            defs.append(f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="0" y1="{grad[2]}" x2="0" y2="{grad[3]}">'
                        f'<stop offset="0" stop-color="{grad[0]}"/><stop offset="1" stop-color="{grad[1]}"/></linearGradient>')
            fill = f"url(#{gid})"
        rule = ' fill-rule="evenodd"' if d in EVEN_ODD else ""
        op = f' fill-opacity="{alpha}"' if alpha != 1 else ""
        body.append(f'<path d="{d}" fill="{fill}"{op}{rule}/>')
    tile = rrect(0, 0, 100, 100, 22) if rounded else "M0,0 H100 V100 H0 Z"
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="1024" height="1024">\n'
            f'<defs>{"".join(defs)}</defs>\n'
            f'<path d="{tile}" fill="url(#bg)"/>\n<path d="{tile}" fill="url(#glow)"/>\n'
            '<g transform="translate(50 50) scale(0.84) translate(-50 -52)">\n'
            + "\n".join(body) + "\n</g>\n</svg>\n")


VD_HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n'
           '<!-- Generated by art/generate_icons.py. Do not edit. -->\n'
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           '    xmlns:aapt="http://schemas.android.com/aapt"\n'
           '    android:width="108dp" android:height="108dp"\n'
           '    android:viewportWidth="108" android:viewportHeight="108">\n')


def vd_path(d, fill, alpha=1.0, grad=None, even_odd=False, indent="        "):
    attrs = [f'android:pathData="{d}"']
    if even_odd:
        attrs.append('android:fillType="evenOdd"')
    if alpha != 1:
        attrs.append(f'android:fillAlpha="{alpha}"')
    if not grad:
        attrs.append(f'android:fillColor="{fill}"')
        return f'{indent}<path ' + f"\n{indent}    ".join(attrs) + " />\n"
    return (f'{indent}<path ' + f"\n{indent}    ".join(attrs) + ">\n"
            f'{indent}    <aapt:attr name="android:fillColor">\n'
            f'{indent}        <gradient android:type="linear" android:startX="0" android:startY="{grad[2]}"\n'
            f'{indent}            android:endX="0" android:endY="{grad[3]}"\n'
            f'{indent}            android:startColor="{grad[0]}" android:endColor="{grad[1]}" />\n'
            f'{indent}    </aapt:attr>\n{indent}</path>\n')


def android():
    res = "app/androidApp/src/main/res/drawable/"
    # The character stays inside the 66 dp safe circle of the 108 dp icon.
    group = '    <group android:scaleX="0.7" android:scaleY="0.7" android:translateX="19" android:translateY="17.6">\n'
    fg = VD_HEAD + group + "".join(vd_path(d, f, a, g, d in EVEN_ODD) for d, f, a, g in SHAPES) + "    </group>\n</vector>\n"
    write(res + "ic_launcher_foreground.xml", fg)

    bg = VD_HEAD + vd_path("M0,0 H108 V108 H0 Z", None, grad=(BG_TOP, BG_BOTTOM, 0, 108), indent="    ") + "</vector>\n"
    write(res + "ic_launcher_background.xml", bg)

    # Themed icons tint one color: the box is solid, the face is cut out of it.
    face = " ".join(EYES + [MOUTH_PATH])
    mono = (VD_HEAD + group
            + vd_path(HANDLE, "#FFFFFFFF", even_odd=True)
            + vd_path(LID, "#FFFFFFFF")
            + vd_path(BODY + " " + face, "#FFFFFFFF", even_odd=True)
            + vd_path(" ".join(PUPILS), "#FFFFFFFF")
            + vd_path(TONGUE_PATH, "#FFFFFFFF")
            + "    </group>\n</vector>\n")
    write(res + "ic_launcher_monochrome.xml", mono)


def ios(icon_svg):
    folder = "app/iosApp/iosApp/Assets.xcassets/"
    write(folder + "Contents.json", '{\n  "info" : { "author" : "xcode", "version" : 1 }\n}\n')
    write(folder + "AppIcon.appiconset/Contents.json",
          '{\n  "images" : [\n    {\n      "filename" : "AppIcon.png",\n      "idiom" : "universal",\n'
          '      "platform" : "ios",\n      "size" : "1024x1024"\n    }\n  ],\n'
          '  "info" : { "author" : "xcode", "version" : 1 }\n}\n')
    png = os.path.join(ROOT, folder, "AppIcon.appiconset/AppIcon.png")
    if shutil.which("rsvg-convert") is None:
        print("rsvg-convert not found; skipping", png)
        return
    # iOS rejects an icon with transparency, so flatten it on black.
    subprocess.run(["rsvg-convert", "-w", "1024", "-h", "1024", "-b", "#000000", "-o", png, icon_svg], check=True)


def main():
    logo = svg(rounded=True)
    write("art/logo.svg", logo)
    write("docs/assets/logo.svg", logo)
    icon = write("art/icon.svg", svg(rounded=False))
    android()
    ios(icon)


if __name__ == "__main__":
    main()
